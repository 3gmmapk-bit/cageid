class Athlete {
  final String id;
  final String name;
  final String nickname;
  final String gym;
  final String weightClass;
  final int wins;
  final int losses;
  final int draws;

  Athlete({
    required this.id,
    required this.name,
    required this.nickname,
    required this.gym,
    required this.weightClass,
    required this.wins,
    required this.losses,
    required this.draws,
  });
}